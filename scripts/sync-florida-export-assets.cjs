// Run with --check in verification, or without arguments after editing an SVG.
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..", "public");
const bundlePath = path.join(root, "js/FloridaExportAssetData.js");
const assets = {};
for (const folder of ["FDOT", "CFX"]) {
  const relativeFolder = `img/shields/United States/Florida/${folder}`;
  for (const name of fs.readdirSync(path.join(root, relativeFolder)).sort()) {
    if (!name.endsWith(".svg")) continue;
    const key = `${relativeFolder}/${name}`;
    assets[key] = "data:image/svg+xml;base64," +
      fs.readFileSync(path.join(root, key)).toString("base64");
  }
}
for (const name of ["FLTurnpike-Toll.svg", "FLToll-Old.svg", "FLCFXToll-Old.svg", "FLToll-Selmon.png"]) {
  const asset = `img/shields/United States/Florida/${name}`;
  const mime = name.endsWith(".png") ? "image/png" : "image/svg+xml";
  assets[asset] = `data:${mime};base64,` + fs.readFileSync(path.join(root, asset)).toString("base64");
}
// A tracked supplement, independent of the optional ignored export bundle.
const source = "/* Generated by scripts/sync-florida-export-assets.cjs. */\n" +
  "window.SIGNMAKER_EXPORT_ASSETS = Object.assign(window.SIGNMAKER_EXPORT_ASSETS || {}, " +
  JSON.stringify(assets, null, 2) + ");\n";
if (process.argv.includes("--check")) {
  if (!fs.existsSync(bundlePath) || fs.readFileSync(bundlePath, "utf8") !== source) {
    console.error("Florida export bundle is missing or stale; run this script without --check.");
    process.exitCode = 1;
  } else {
    console.log(`All ${Object.keys(assets).length} Florida assets match the export bundle.`);
  }
} else {
  fs.writeFileSync(bundlePath, source);
  console.log(`Bundled ${Object.keys(assets).length} Florida assets.`);
}
